#include "valdi/linux/LinuxRuntime.hpp"
#include "valdi/runtime/JavaScript/JavaScriptRuntime.hpp"
#include "valdi/runtime/Runtime.hpp"
#include "valdi/runtime/Resources/ValdiModuleArchive.hpp"
#include "valdi/standalone_runtime/StandaloneMainQueue.hpp"
#include "valdi/standalone_runtime/StandaloneResourceLoader.hpp"
#include "valdi/standalone_runtime/ValdiStandaloneRuntime.hpp"
#include "valdi_core/cpp/Utils/StringCache.hpp"
#include "valdi_modules/sdk_service/sdk_service.hpp"

#include <chrono>
#include <iostream>
#include <string>
#include <string_view>

using namespace Valdi;
using namespace snap::valdi_modules::sdk_service;

// A qualification fixture for the existing C++ API, not a stable service API.
int main(int argc, const char** argv) {
    const std::string mode = argc > 1 ? argv[1] : "success";
    for (int cycle = 0; cycle < 3; cycle++) {
        auto runtime = ValdiLinux::createLinuxRuntime(false, true);
        auto queue = runtime->getMainQueue();
        auto js = runtime->getRuntime().getJavaScriptRuntime();
        if (mode == "missing" || mode == "corrupt" || mode == "entry-error") {
            if (argc > 2) {
                runtime->getResourceLoader().addModuleSearchDirectory(
                    StringCache::getGlobal().makeString(std::string_view(argv[2])));
            }
            const auto path = mode == "entry-error" ? STRING_LITERAL("sdk_service/src/Failure")
                              : mode == "corrupt" ? STRING_LITERAL("corrupt/src/Service")
                                                  : STRING_LITERAL("missing/src/Service");
            if (mode == "corrupt") {
                const auto bytes = runtime->getResourceLoader().loadModuleContent(STRING_LITERAL("corrupt.valdimodule"));
                if (!bytes || std::string_view(reinterpret_cast<const char*>(bytes.value().data()),
                                                bytes.value().size()) != "not a Valdi module") {
                    std::cerr << "Corrupt fixture bytes were not found by the resource loader\n";
                    return 1;
                }
                const auto parsed = ValdiModuleArchive::decompress(bytes.value().data(), bytes.value().size());
                if (parsed || parsed.error().toString().find("magic is incorrect") == std::string::npos) {
                    std::cerr << "Corrupt fixture did not produce the expected archive-format error\n";
                    return 1;
                }
                std::cout << "resource-error corrupt: " << parsed.error().toString() << '\n';
            } else if (mode == "missing") {
                const auto bytes = runtime->getResourceLoader().loadModuleContent(STRING_LITERAL("missing.valdimodule"));
                if (bytes || bytes.error().toString().find("Could not find module") == std::string::npos) {
                    std::cerr << "Missing fixture unexpectedly resolved through the resource loader\n";
                    return 1;
                }
                std::cout << "resource-error missing: " << bytes.error().toString() << '\n';
            }
            const auto result = js->evalModuleSync(path, false);
            if (result) {
                std::cerr << "Expected module failure: " << mode << '\n';
                return 1;
            }
            const auto error = result.error().toString();
            const std::string_view expected = mode == "entry-error" ? "sdk fixture entry point failed"
                                                : mode == "corrupt" ? "No item named 'src/Service.js' in module 'corrupt'"
                                                                    : "No item named 'src/Service.js' in module 'missing'";
            if (error.find(expected) == std::string::npos) {
                std::cerr << "Unexpected module failure for " << mode << ": " << error << '\n';
                return 1;
            }
            std::cout << "expected-error " << mode << ": " << error << '\n';
            js = nullptr;
            runtime = nullptr;
            queue->dispose();
            continue;
        }
        auto objects = js->createNativeObjectsManager("linux-sdk-consumer");
        bool complete = false;
        bool accepting = true;
        int cancelledCallbacks = 0;
        double actual = 0;
        const auto pending = queue->enqueue([&]() { cancelledCallbacks++; }, std::chrono::hours(1));
        {
            // Both declarations and the invocation trampoline are generated by
            // Valdi. The service's TypeScript body was compiled through TSN.
            auto answer = Answer::resolve(*js, objects);
            auto calculate = Calculate::resolve(*js, objects);
            if (!answer || !calculate || answer.value()() != 42) {
                std::cerr << "Generated native function resolution/invocation failed\n";
                return 2;
            }
            Request request(20, 22);
            calculate.value()(request, [&](double result) {
                // Native callbacks arrive on the JS queue. The host owns its
                // main queue and marshals completion without blocking it.
                queue->enqueue([&, result]() {
                    if (accepting) {
                        actual = result;
                        complete = true;
                    }
                });
            });
            const auto deadline = std::chrono::steady_clock::now() + std::chrono::seconds(5);
            while (!complete && std::chrono::steady_clock::now() < deadline) {
                queue->runNextTask(deadline);
            }
            if (!complete || actual != 42) {
                std::cerr << "Native completion failed or timed out\n";
                return 3;
            }
        }
        accepting = false;
        queue->cancel(pending.id);
        js->destroyNativeObjectsManager(objects);
        objects = nullptr;
        js = nullptr;
        runtime = nullptr;
        queue->dispose();
        if (cancelledCallbacks != 0 || queue->enqueue([]() {}).id != 0) {
            std::cerr << "Cancelled or post-disposal work was accepted\n";
            return 4;
        }
    }
    std::cout << "PASS " << mode << " 3 runtime cycles\n";
    return 0;
}
